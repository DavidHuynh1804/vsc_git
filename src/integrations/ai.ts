import { commands, events } from "@/bindings";
import { AiConsentDataSource, AiDataSource } from "./types";

const PROVIDER_DEFAULT_MODELS: Record<string, string[]> = {
  claude: ["claude-haiku-5-5", "claude-sonnet-5-5"],
  openai: ["gpt-4o", "gpt-4o-mini", "o3-mini"],
  ollama: ["llama3.2", "qwen2.5-coder", "mistral"],
};

export class MockAiDataSource implements AiDataSource {
  public lastTestedProvider: string | null = null;
  public lastSavedKeyProvider: string | null = null;
  // Crucial: key is never stored in persistent state or logged.
  // In mock, we only remember whether a key was submitted.
  private hasKeyForProvider = new Set<string>();

  async listModels(provider: string, _baseUrl?: string | null): Promise<string[]> {
    return PROVIDER_DEFAULT_MODELS[provider.toLowerCase()] ?? ["default-model"];
  }

  async setAiKey(provider: string, key: string): Promise<void> {
    if (key.trim()) {
      this.hasKeyForProvider.add(provider);
      this.lastSavedKeyProvider = provider;
    }
  }

  async testProvider(provider: string, model?: string, _baseUrl?: string | null): Promise<string> {
    this.lastTestedProvider = provider;
    return `Connection to ${provider} (${model ?? "default"}) succeeded: AI is ready for commit and PR generation.`;
  }

  async generatePr(
    base: string,
    head: string,
    onChunk: (chunk: string) => void
  ): Promise<{ title: string; body: string }> {
    const title = `feat: integrate changes from ${head} into ${base}`;
    const chunks = [
      "## Summary of Changes\n\n",
      `- Merges branch \`${head}\` into \`${base}\`.\n`,
      "- Adds robust integration and settings interfaces.\n",
      "- Full tests included.\n\n",
      "## Testing Done\n\n",
      "- Unit tests and integration suite verified.\n",
    ];

    let fullBody = "";
    for (const chunk of chunks) {
      fullBody += chunk;
      onChunk(chunk);
      await Promise.resolve();
    }
    return { title, body: fullBody };
  }
  async generateCommit(onChunk?: (chunk: string) => void): Promise<string> {
    const message = "feat(app): add commit message generated by mock AI";
    onChunk?.(message);
    return message;
  }
}

export class TauriAiDataSource implements AiDataSource {
  async listModels(provider: string, baseUrl?: string | null): Promise<string[]> {
    const res = await commands.aiListModels(provider, baseUrl ?? null);
    if (res.status === "error") {
      throw new Error(res.error.message);
    }
    return res.data;
  }

  async setAiKey(provider: string, key: string): Promise<void> {
    const res = await commands.setAiKey(provider, key);
    if (res.status === "error") {
      throw new Error(res.error.message);
    }
  }

  async testProvider(provider: string, model?: string, baseUrl?: string | null): Promise<string> {
    const res = await commands.testAiProvider(provider, model ?? null, baseUrl ?? null);
    if (res.status === "error") {
      throw new Error(res.error.message);
    }
    return res.data;
  }

  async generatePr(
    base: string,
    head: string,
    onChunk: (chunk: string) => void
  ): Promise<{ title: string; body: string }> {
    const res = await commands.aiGeneratePr(base, head);
    if (res.status === "error") {
      throw new Error(res.error.message);
    }
    const jobId = res.data;
    let fullOutput = "";
    const { promise, resolve, reject } = Promise.withResolvers<void>();
    let unlistenChunk: (() => void) | undefined;
    let unlistenDone: (() => void) | undefined;

    const cleanup = () => {
      if (unlistenChunk) unlistenChunk();
      if (unlistenDone) unlistenDone();
    };

    events.jobChunk
      .listen((e) => {
        if (e.payload.id === jobId) {
          fullOutput += e.payload.chunk;
          onChunk(e.payload.chunk);
        }
      })
      .then((u) => {
        unlistenChunk = u;
      });

    events.jobDone
      .listen((e) => {
        if (e.payload.id === jobId) {
          cleanup();
          if (e.payload.success) {
            resolve();
          } else {
            reject(new Error(e.payload.error ?? "Failed to generate PR"));
          }
        }
      })
      .then((u) => {
        unlistenDone = u;
      });

    await promise;
    const lines = fullOutput.trim().split("\n");
    const title = lines[0] ?? "";
    const body = lines.slice(1).join("\n").trim();
    return { title, body };
  }

  async generateCommit(onChunk?: (chunk: string) => void): Promise<string> {
    const res = await commands.aiGenerateCommit();
    if (res.status === "error") {
      throw new Error(res.error.message);
    }
    const jobId = res.data;
    let fullOutput = "";
    const { promise, resolve, reject } = Promise.withResolvers<string>();
    let unlistenChunk: (() => void) | undefined;
    let unlistenDone: (() => void) | undefined;

    const cleanup = () => {
      if (unlistenChunk) unlistenChunk();
      if (unlistenDone) unlistenDone();
    };

    events.jobChunk
      .listen((e) => {
        if (e.payload.id === jobId) {
          fullOutput += e.payload.chunk;
          onChunk?.(e.payload.chunk);
        }
      })
      .then((u) => {
        unlistenChunk = u;
      });

    events.jobDone
      .listen((e) => {
        if (e.payload.id === jobId) {
          cleanup();
          if (e.payload.success) {
            resolve(fullOutput);
          } else {
            reject(new Error(e.payload.error ?? "Failed to generate commit message"));
          }
        }
      })
      .then((u) => {
        unlistenDone = u;
      });

    return promise;
  }
}

export class TauriAiConsentDataSource implements AiConsentDataSource {
  private cache = new Map<string, boolean>();

  constructor() {
    this.sync().catch(() => {});
  }

  async sync(): Promise<void> {
    const res = await commands.getSettings();
    if (res.status === "ok" && res.data["ai.consents"]) {
      for (const [repo, providers] of Object.entries(res.data["ai.consents"])) {
        for (const p of providers) {
          this.cache.set(`${repo}:${p.toLowerCase()}`, true);
        }
      }
    }
  }

  hasConsent(repoPath: string, provider: string): boolean {
    const k = `${repoPath}:${provider.toLowerCase()}`;
    if (this.cache.has(k)) {
      return this.cache.get(k) === true;
    }
    commands
      .aiHasConsent(repoPath, provider)
      .then((res) => {
        if (res.status === "ok") {
          this.cache.set(k, res.data);
        }
      })
      .catch(() => {});
    return false;
  }

  setConsent(repoPath: string, provider: string, granted: boolean): void {
    const k = `${repoPath}:${provider.toLowerCase()}`;
    this.cache.set(k, granted);
    commands.aiSetConsent(repoPath, provider, granted).catch(() => {});
  }
}

export class LocalStorageAiConsentDataSource implements AiConsentDataSource {
  private memoryMap = new Map<string, boolean>();

  private makeKey(repoPath: string, provider: string): string {
    return `vsc_git_ai_consent:${repoPath}:${provider}`;
  }

  hasConsent(repoPath: string, provider: string): boolean {
    const key = this.makeKey(repoPath, provider);
    try {
      if (typeof window !== "undefined" && window.localStorage) {
        const val = window.localStorage.getItem(key);
        if (val !== null) {
          return val === "true";
        }
      }
    } catch {
      // Fallback to memory
    }
    return this.memoryMap.get(key) === true;
  }

  setConsent(repoPath: string, provider: string, granted: boolean): void {
    const key = this.makeKey(repoPath, provider);
    try {
      if (typeof window !== "undefined" && window.localStorage) {
        window.localStorage.setItem(key, granted ? "true" : "false");
      }
    } catch {
      // Fallback to memory
    }
    this.memoryMap.set(key, granted);
  }
}

export const defaultAiDataSource =
  import.meta.env?.VITE_USE_MOCK === "true"
    ? new MockAiDataSource()
    : new TauriAiDataSource();
export const defaultAiConsentDataSource: AiConsentDataSource =
  import.meta.env?.VITE_USE_MOCK === "true"
    ? new LocalStorageAiConsentDataSource()
    : new TauriAiConsentDataSource();
